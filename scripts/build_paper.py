ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "results" / "tables"
PUBLISHED = ROOT / "paper" / "published-results"
DATA = PUBLISHED if (PUBLISHED / "final_report.json").exists() else TABLES
PAPER = ROOT / "paper"
FIGURES = PAPER / "figures"
GENERATED = PAPER / "generated"


def _load(name: str) -> dict:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def _fmt(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}f}"


def build_numbers() -> None:
    v1 = _load("dro_experiment_summary.json")
    v1_analysis = _load("dro_experiment_analysis.json")
    b0 = _load("ridge_b0_summary.json")
    v2 = _load("v2_summary_dev.json")
    v2_gate = _load("v2_uncertainty_audit.json")
    v3 = _load("v3_summary_dev.json")
    v3_gate = _load("v3_sigma_audit.json")
    final = _load("final_report.json")
    gate_summary = pd.read_csv(DATA / "gate_power_summary.csv")
    gate_reeval = _load("gate_reevaluation.json")

    def gate_row(assets: int, beta: float) -> dict:
        match = gate_summary[
            (gate_summary["n_assets"] == assets)
            & (gate_summary["n_dates"] == 179)
            & (gate_summary["beta"] == beta)
            & (gate_summary["signal"] == "linear")
        ]
        return match.iloc[0].to_dict()

    g00 = gate_row(72, 0.0)
    g02 = gate_row(72, 0.2)
    g05 = gate_row(72, 0.5)
    v1_passes = sum(1 for row in gate_reeval["v1_features"] if row["passes"])
    v1_total = len(gate_reeval["v1_features"])
    p_min = min(row["pvalue"] for row in gate_reeval["v1_features"])

    def strategy(summary: dict, name: str) -> dict:
        row = summary[name]
        return {
            "sharpe": row["net_sharpe"],
            "mdd": row["max_drawdown"],
            "cvar": row["cvar95"],
            "turnover": row["annualized_turnover"],
            "cost_drag": row["annualized_cost_drag"],
        }

    lines = [
        "// Generated by scripts/build_paper.py. Do not edit by hand.",
        "#let v1 = (",
        f"  m1: (sharpe: {strategy(v1, 'M1_reduced')['sharpe']:.12f}, mdd: {strategy(v1, 'M1_reduced')['mdd']:.12f}, cvar: {strategy(v1, 'M1_reduced')['cvar']:.12f}, turnover: {strategy(v1, 'M1_reduced')['turnover']:.12f}),",
        f"  b5: (sharpe: {strategy(v1, 'B5_DRO_point')['sharpe']:.12f}, mdd: {strategy(v1, 'B5_DRO_point')['mdd']:.12f}, cvar: {strategy(v1, 'B5_DRO_point')['cvar']:.12f}, turnover: {strategy(v1, 'B5_DRO_point')['turnover']:.12f}),",
        f"  b1: (sharpe: {strategy(v1, 'B1_equal_weight')['sharpe']:.12f}, mdd: {strategy(v1, 'B1_equal_weight')['mdd']:.12f}, cvar: {strategy(v1, 'B1_equal_weight')['cvar']:.12f}, turnover: {strategy(v1, 'B1_equal_weight')['turnover']:.12f}),",
        ")",
        "#let v1_boot = (",
        f"  sharpe_diff: {v1_analysis['comparisons']['B5_DRO_point']['sharpe_diff_mean']:.12f},",
        f"  sharpe_ci: ({v1_analysis['comparisons']['B5_DRO_point']['sharpe_diff_ci90'][0]:.12f}, {v1_analysis['comparisons']['B5_DRO_point']['sharpe_diff_ci90'][1]:.12f}),",
        f"  mdd_diff: {v1_analysis['comparisons']['B5_DRO_point']['mdd_diff_mean']:.12f},",
        f"  mdd_ci: ({v1_analysis['comparisons']['B5_DRO_point']['mdd_diff_ci90'][0]:.12f}, {v1_analysis['comparisons']['B5_DRO_point']['mdd_diff_ci90'][1]:.12f}),",
        f"  cvar_diff: {v1_analysis['comparisons']['B5_DRO_point']['cvar_diff_mean']:.12f},",
        f"  cvar_ci: ({v1_analysis['comparisons']['B5_DRO_point']['cvar_diff_ci90'][0]:.12f}, {v1_analysis['comparisons']['B5_DRO_point']['cvar_diff_ci90'][1]:.12f}),",
        f"  rel_mdd: {v1_analysis['verdict']['H1_tail_improvement']['relative_mdd_ci90'][0]:.12f},",
        f"  rel_mdd_ci: ({v1_analysis['verdict']['H1_tail_improvement']['relative_mdd_ci90'][0]:.12f}, {v1_analysis['verdict']['H1_tail_improvement']['relative_mdd_ci90'][1]:.12f}),",
        ")",
        f"#let b0 = (r2: {b0['pooled_oos_r2']:.12f}, ic: {b0['mean_rank_ic']:.12f}, t: {b0['ic_t_stat']:.12f})",
        f"#let v2 = (m1_sharpe: {v2['M1_v2']['net_sharpe']:.12f}, m1_mdd: {v2['M1_v2']['max_drawdown']:.12f}, m1_cvar: {v2['M1_v2']['cvar95']:.12f}, b5_sharpe: {v2['B5_uncond_sigma']['net_sharpe']:.12f}, b5_mdd: {v2['B5_uncond_sigma']['max_drawdown']:.12f}, b5_cvar: {v2['B5_uncond_sigma']['cvar95']:.12f})",
        f"#let v2_gate = (pass: {v2_gate['features'][0]['pass_rate']:.12f}, coverage_val: {v2_gate['coverage']['mean_validation_coverage']:.12f}, coverage_test: {v2_gate['coverage']['mean_test_coverage']:.12f})",
        f"#let v3 = (m1_sharpe: {v3['M1_v3']['net_sharpe']:.12f}, m1_mdd: {v3['M1_v3']['max_drawdown']:.12f}, m1_cvar: {v3['M1_v3']['cvar95']:.12f}, b5_sharpe: {v3['B5_uncond_sigma']['net_sharpe']:.12f}, b5_mdd: {v3['B5_uncond_sigma']['max_drawdown']:.12f}, b5_cvar: {v3['B5_uncond_sigma']['cvar95']:.12f})",
        f"#let v3_gate = (pass: {v3_gate['sigma']['pass_rate']:.12f}, mean_sigma: {v3_gate['calibration']['mean_sigma']:.12f}, mean_realized: {v3_gate['calibration']['mean_realized_abs']:.12f}, corr: {v3_gate['calibration']['correlation']:.12f}, decile_spread: {v3_gate['calibration']['decile_spread']:.12f})",
        f"#let dsr = (m1: {final['deflated_sharpe']['M1_reduced']['deflated_sharpe_probability']:.12f}, b5: {final['deflated_sharpe']['B5_DRO_point']['deflated_sharpe_probability']:.12f}, b1: {final['deflated_sharpe']['B1_equal_weight']['deflated_sharpe_probability']:.12f})",
        f"#let gate = (mi_pass_00_72: {g00['mi_pass_rate']:.12f}, mi_pass_02_72: {g02['mi_pass_rate']:.12f}, mi_pass_05_72: {g05['mi_pass_rate']:.12f}, mi_power_00_72: {g00['mi_power']:.12f}, mi_power_02_72: {g02['mi_power']:.12f}, mi_power_05_72: {g05['mi_power']:.12f}, pooled_power_00_72: {g00['pooled_power']:.12f}, pooled_power_02_72: {g02['pooled_power']:.12f}, pooled_power_05_72: {g05['pooled_power']:.12f}, decile_pass_00_72: {g00['decile_pass_rate']:.12f}, decile_pass_05_72: {g05['decile_pass_rate']:.12f}, decile_power_00_72: {g00['decile_power']:.12f}, decile_power_05_72: {g05['decile_power']:.12f}, v1_passes: {v1_passes}, v1_total: {v1_total}, v2_pooled_p: {gate_reeval['v2_sigma']['pvalue']:.12f}, v3_pooled_p: {gate_reeval['v3_sigma']['pvalue']:.12f}, p_min: {p_min:.12f})",
    ]
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / "numbers.typ").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _style() -> None:
    plt.rcParams.update(
        {
            "figure.facecolor": "white",
            "axes.facecolor": "white",
            "axes.edgecolor": "#b8b8b8",
            "axes.labelcolor": "#202020",
            "text.color": "#202020",
            "xtick.color": "#4a4a4a",
            "ytick.color": "#4a4a4a",
            "font.family": "DejaVu Sans",
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )


def build_figures() -> None:
    _style()
    FIGURES.mkdir(parents=True, exist_ok=True)

    returns = pd.read_csv(DATA / "dro_experiment_returns.csv")
    rf = pd.read_parquet(ROOT / "data" / "raw" / "risk_free.parquet")
    rf = rf.set_index("date")["rf"].sort_index()
    pivot = returns.pivot(index="date", columns="strategy", values="net_return").sort_index()
    pivot.index = pd.to_datetime(pivot.index)
    rf = rf.reindex(pivot.index)
    excess = (1.0 + pivot).div(1.0 + rf, axis=0) - 1.0
    cumulative = (1.0 + excess).cumprod()

    fig, ax = plt.subplots(figsize=(8.4, 4.2), dpi=200)
    colors = {"M1_reduced": "#1f5c99", "B5_DRO_point": "#c46a1b", "B1_equal_weight": "#6b6b6b"}
    labels = {
        "M1_reduced": "M1 reduced (uncertainty)",
        "B5_DRO_point": "B5 point DRO",
        "B1_equal_weight": "1/N",
    }
    for name in ("M1_reduced", "B5_DRO_point", "B1_equal_weight"):
        ax.plot(cumulative.index, cumulative[name], label=labels[name], color=colors[name], linewidth=1.8)
    ax.set_title("Cumulative net excess return — metric path, not an investable return", fontsize=10.5, loc="left")
    ax.set_ylabel("Growth of 1")
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    ax.grid(axis="y", color="#e6e6e6", linewidth=0.8)
    ax.tick_params(labelsize=8)
    fig.tight_layout()
    fig.savefig(FIGURES / "v1_cumulative.png", bbox_inches="tight")
    plt.close(fig)

    v2_gate = _load("v2_uncertainty_audit.json")
    v3_gate = _load("v3_sigma_audit.json")
    pass_rates = [v2_gate["features"][0]["pass_rate"], v3_gate["sigma"]["pass_rate"]]
    fig, ax = plt.subplots(figsize=(6.6, 3.4), dpi=200)
    bars = ax.bar(["v2\nconformal quantiles", "v3\nconditional tail risk"], pass_rates, color=["#9a9a9a", "#9a9a9a"], width=0.5)
    ax.axhline(0.80, color="#9c3527", linewidth=1.4, linestyle="--")
    ax.text(1.55, 0.815, "frozen gate: 80%", color="#9c3527", fontsize=8, ha="right")
    for bar, value in zip(bars, pass_rates, strict=False):
        ax.text(bar.get_x() + bar.get_width() / 2, value + 0.02, f"{value:.1%}", ha="center", fontsize=10, fontweight="bold")
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("Date-level pass rate")
    ax.set_title("Pre-holdout information gates", fontsize=10.5, loc="left")
    ax.grid(axis="y", color="#e6e6e6", linewidth=0.8)
    ax.tick_params(labelsize=8)
    fig.tight_layout()
    fig.savefig(FIGURES / "gate_pass_rates.png", bbox_inches="tight")
    plt.close(fig)

    sigma = pd.read_parquet(DATA / "v3_sigma_dev.parquet").dropna(subset=["sigma", "realized_abs"])
    sigma["decile"] = pd.qcut(sigma["sigma"], 10, labels=False, duplicates="drop")
    decile = sigma.groupby("decile")["realized_abs"].mean()
    fig, ax = plt.subplots(figsize=(6.6, 3.4), dpi=200)
    ax.bar(decile.index + 1, decile.values, color="#1f5c99", width=0.72)
    ax.set_xlabel("Predicted tail-risk decile")
    ax.set_ylabel("Mean realized |excess return|")
    ax.set_title("Calibration is good — per-date information is not stable", fontsize=10.5, loc="left")
    ax.grid(axis="y", color="#e6e6e6", linewidth=0.8)
    ax.tick_params(labelsize=8)
    fig.tight_layout()
    fig.savefig(FIGURES / "v3_calibration.png", bbox_inches="tight")
    plt.close(fig)

    gate = pd.read_csv(DATA / "gate_power_summary.csv")
    gate = gate[
        (gate["n_assets"] == 72)
        & (gate["n_dates"] == 179)
        & (gate["signal"] == "linear")
    ].sort_values("beta")
    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.6), dpi=200, gridspec_kw={"width_ratios": [1.1, 1.0]})
    axes[0].plot(gate["beta"], gate["mi_pass_rate"], marker="o", color="#1f5c99", label="80% MI gate")
    axes[0].plot(gate["beta"], gate["decile_pass_rate"], marker="s", color="#c46a1b", label="decile gate")
    axes[0].axhline(0.80, color="#9c3527", linestyle="--", linewidth=1.2)
    axes[0].text(0.02, 0.82, "80% threshold", color="#9c3527", fontsize=7.5)
    axes[0].set_xlabel("Signal strength β")
    axes[0].set_ylabel("Date-level pass rate")
    axes[0].set_ylim(0, 1.0)
    axes[0].set_title("Per-date pass rate (72 assets)", fontsize=9.5, loc="left")
    axes[0].legend(frameon=False, fontsize=7.5, loc="upper left")
    axes[0].grid(axis="y", color="#e6e6e6", linewidth=0.8)

    betas = [0.2, 0.5]
    labels = ["β=0.2\n(R²≈3.8%)", "β=0.5\n(R²≈20%)"]
    x = np.arange(len(betas))
    width = 0.24
    mi = [gate[gate["beta"] == b]["mi_power"].iloc[0] for b in betas]
    pooled = [gate[gate["beta"] == b]["pooled_power"].iloc[0] for b in betas]
    decile = [gate[gate["beta"] == b]["decile_power"].iloc[0] for b in betas]
    axes[1].bar(x - width, mi, width, label="80% MI", color="#9a9a9a")
    axes[1].bar(x, pooled, width, label="pooled MI", color="#1f5c99")
    axes[1].bar(x + width, decile, width, label="decile", color="#c46a1b")
    axes[1].set_xticks(x, labels, fontsize=8)
    axes[1].set_ylim(0, 1.05)
    axes[1].set_ylabel("Gate power")
    axes[1].set_title("Gate power (72 assets)", fontsize=9.5, loc="left")
    axes[1].legend(frameon=False, fontsize=7.5, loc="upper right")
    axes[1].grid(axis="y", color="#e6e6e6", linewidth=0.8)
    fig.tight_layout()
    fig.savefig(FIGURES / "gate_power.png", bbox_inches="tight")
    plt.close(fig)


def build_linkedin_card() -> None:
    _style()
    fig, ax = plt.subplots(figsize=(8.0, 10.0), dpi=180)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")
    fig.patch.set_facecolor("#f7f5f0")
    ax.add_patch(Rectangle((0, 0), 1, 1, facecolor="#f7f5f0", edgecolor="none"))

    ax.text(0.07, 0.94, "EPISTEMIC-AWARE DRO  ·  72 US ETFs  ·  2010–2024", fontsize=9, color="#6b6b6b", family="DejaVu Sans")
    ax.text(0.07, 0.865, "Three pre-registered attempts.", fontsize=26, fontweight="bold", color="#1a1a1a")
    ax.text(0.07, 0.815, "The holdout is still untouched.", fontsize=26, fontweight="bold", color="#1f5c99")
    ax.text(0.07, 0.765, "What I learned trying to make uncertainty pay.", fontsize=12, color="#4a4a4a")

    boxes = [
        ("v1  Epistemic uncertainty", "H1 / H3 fail  ·  H2 pass", "Ridge mean + bootstrap σ\nno stable mean or uncertainty signal", "#9c3527"),
        ("v2  Conformal quantiles", "Stopped before holdout", "coverage 0.899 / 0.859\ninformation gate 65.4% < 80%", "#b07a1e"),
        ("v3  Conditional tail risk", "Stopped before holdout", "calibration 4.29% vs 4.30%\ninformation gate 43.0% < 80%", "#b07a1e"),
    ]
    y = 0.70
    for title, verdict, detail, color in boxes:
        ax.add_patch(FancyBboxPatch((0.07, y - 0.105), 0.86, 0.115, boxstyle="round,pad=0.012,rounding_size=0.012", facecolor="white", edgecolor="#dddddd", linewidth=0.8))
        ax.text(0.10, y - 0.025, title, fontsize=12.5, fontweight="bold", color="#1a1a1a")
        ax.text(0.10, y - 0.055, verdict, fontsize=10.5, color=color, fontweight="bold")
        ax.text(0.10, y - 0.090, detail, fontsize=8.8, color="#555555", linespacing=1.35)
        y -= 0.14

    ax.add_patch(FancyBboxPatch((0.07, 0.13), 0.86, 0.12, boxstyle="round,pad=0.012,rounding_size=0.012", facecolor="#1f5c99", edgecolor="none"))
    ax.text(0.10, 0.205, "Calibration ≠ information.  Gates > narratives.", fontsize=14, fontweight="bold", color="white")
    ax.text(0.10, 0.165, "Three negative results. Zero holdout touches. The apparatus is the result.", fontsize=9.3, color="#dce8f3")

    ax.text(0.07, 0.075, "Paper + code: github.com/kira-ml/epistemic-dro", fontsize=8.5, color="#6b6b6b")
    ax.text(0.07, 0.045, "Not investment advice. No alpha claim. No live deployment.", fontsize=7.8, color="#8a8a8a")
    fig.savefig(PAPER / "linkedin_card.png", bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close(fig)


def compile_paper() -> None:
    import typst

    typst.compile(str(PAPER / "paper.typ"), output=str(PAPER / "mini_paper.pdf"))
    typst.compile(str(PAPER / "carousel.typ"), output=str(PAPER / "linkedin_carousel.pdf"))


def make_one_pager_pdf() -> None:
    from PIL import Image

    Image.open(PAPER / "linkedin_card.png").convert("RGB").save(
        PAPER / "one_pager.pdf", "PDF", resolution=180.0
    )


if __name__ == "__main__":
    build_numbers()
    build_figures()
    build_linkedin_card()
    compile_paper()
    make_one_pager_pdf()
    print(
        "wrote paper/mini_paper.pdf, paper/linkedin_carousel.pdf, "
        "paper/one_pager.pdf, paper/linkedin_card.png, paper/figures/"
    )
